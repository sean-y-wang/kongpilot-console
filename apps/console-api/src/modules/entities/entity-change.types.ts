import type { EntityActor, EntityType, CredentialKind } from './entities.types';
import type { MutationImpact } from '../mutations/mutation-impact';
import type { RecycleGraph } from '../recycle-bin/graph-capturer.service';
import type { EntityRecycleClosedRestoreCoverage } from '../recycle-bin/entity-recycle-origin-reader.types';

/** Server-derived partition only. HTTP change DTOs never accept these facts.
 * A keyed copy is still not authority: execution requires Root's original
 * private claim and fresh full-graph/current-custody verifier. */
export interface EntityPartialRecycleRestoreSelection {
  readonly version: 1;
  readonly history: EntityRecycleClosedRestoreCoverage;
  readonly presentNodes: readonly Readonly<{ nodeKey: string; beforeHmac: string; basicCustodyHmac?: string }>[];
  readonly remainingNodeKeys: readonly string[];
  readonly selectionHmac: string;
}

/** User intent only. Native paths, methods, manifests and authorization proofs
 * are generated by the server and are never accepted in this DTO. */
export type EntityChangeOperation =
  | { kind: 'entity'; action: 'create'; entityType: EntityType; body: Record<string, unknown> }
  | { kind: 'entity'; action: 'update'; entityType: EntityType; entityId: string; body: Record<string, unknown> }
  | { kind: 'target'; action: 'create'; upstreamId: string; body: Record<string, unknown> }
  | { kind: 'target'; action: 'weight'; upstreamId: string; targetId: string; body: Record<string, unknown> }
  | { kind: 'target'; action: 'health'; upstreamId: string; targetId: string; state: 'healthy' | 'unhealthy' }
  | { kind: 'credential'; action: 'create'; consumerId: string; credentialKind: CredentialKind; body: Record<string, unknown> }
  | { kind: 'credential'; action: 'update'; consumerId: string; credentialKind: CredentialKind; credentialId: string; body: Record<string, unknown> }
  | { kind: 'recycle'; action: 'delete'; entityType: EntityType | 'targets' | 'credentials'; entityId: string; parentId?: string; credentialKind?: CredentialKind; confirmed: true; confirm_name: string }
  | { kind: 'recycle'; action: 'restore'; entryId: string; confirmed: true; confirm_name: string };
export type EntityChangeInput = EntityChangeOperation | { kind: 'batch'; operations: EntityChangeOperation[]; confirmed: true };

export interface EntityPreparationReference { type: string; path: string; before: any | null; permissionAction: 'read' | 'write'; absent?: boolean; purpose?: 'private-parent'; }
/** Runtime preparation is not an authorization capability or persisted intent. */
export interface EntityMutationPreparation {
  actor: EntityActor; type: string; action: 'create' | 'update' | 'health'; nativeId?: string;
  before: any | null; payload: Record<string, any>; parent?: { type: 'consumers' | 'upstreams'; before: any };
  references: EntityPreparationReference[];
  certificateSnis?: EntityPreparationReference[];
}
export interface EntityWriteSchemaMaterial {
  version: 1; clusterId: string; canonicalPath: string; nativeType: string;
  kongVersion: string; adapter: string; clusterRevision: number; payloadHmac: string;
  schemaMaterial: { entity: { name: string; canonicalPath: string; schema: unknown }; plugin?: { name: string; canonicalPath: string; schema: unknown } };
}
export interface EntityChangePacket {
  key: string; order: number; dependencies: string[]; method: 'POST' | 'PATCH' | 'DELETE'; canonicalPath: string;
  nativeType: string; nativeId: string; parentId?: string; credentialKind?: CredentialKind;
  permissionAction: 'write' | 'delete'; mutationAction: 'create' | 'update' | 'delete' | 'restore' | 'mark_healthy' | 'mark_unhealthy';
  body?: Record<string, unknown>; before: unknown | null; bodyHmac: string; beforeHmac: string;
  /** Target history UUID differs from the old logical effective record. */
  originalNativeId?: string;
}
export interface EntityChangePrerequisite {
  type: string; path: string; nativeId?: string; parentId?: string;
  before: unknown | null; absent: boolean; fingerprint: string; permissionAction: 'read' | 'write' | 'delete';
  purpose?: 'private-parent';
}
export type EntityChangeMetadataObligation =
  | { kind: 'entity-index'; packetKey: string; entityType: EntityType }
  | { kind: 'credential-remember'; packetKey: string; consumerId: string; credentialKind: CredentialKind; rawInput: Record<string, unknown> }
  | { kind: 'recycle-archive'; graph: RecycleGraph; graphHmac: string; packetKeys: string[] }
  | { kind: 'recycle-restore'; entryId: string; graph: RecycleGraph; graphHmac: string; packetKeys: string[];
      partialRestore?: EntityPartialRecycleRestoreSelection;
      sealedEntry: { clusterId: string; workspaceId: string; entryId: string; state: string; expiresAt: string;
        payloadHmac: string; nodeManifestHmac: string; restoreMaterialHmac: string } };
export interface PreparedEntityChange {
  version: 1; clusterId: string; workspaceId: string; requesterId: string; permissionVersion: string;
  scope: { transportScope: string; clusterRevision: number; workspaceRevision: number; kongVersion: string; adapter: string };
  request: EntityChangeInput; prerequisites: EntityChangePrerequisite[];
  schemas: EntityWriteSchemaMaterial[]; packets: EntityChangePacket[]; metadataObligations: EntityChangeMetadataObligation[];
  recovery: { state: 'baseline-required'; blockerCodes: string[]; objects: Array<{ type: string; nativeId: string; parentId?: string; restorePayload?: unknown; sourceHashHmac?: string; blockerCodes: string[] }> };
  impact: MutationImpact; changeDigest: string;
}
export interface EntityChangeReview {
  version: 1; clusterId: string; workspaceId: string; changeDigest: string;
  changes: Array<{ entityType: string; nativeId: string; originalNativeId?: string; action: string; before: unknown; after: unknown }>;
  impact: { changedObjects: number; nativePackets: number; traffic: null; trafficAvailability: 'unavailable'; globalPlugin: boolean };
  recovery: { state: 'baseline-required'; blockerCodes: string[] };
}
export type StoredEntitySubjectAction = 'read' | 'write' | 'approve';
export type StoredEntityRevalidationPhase = 'review' | 'submit' | 'approve' | 'claim';
/** Bootstrap-only read policies. Their result contains facts, never a permit.
 * There is deliberately no fallback when managed boundaries are unavailable. */
export interface EntityChangePreparationBoundary {
  assertPacket(input: { clusterId: string; workspaceId: string; transportScope: string; packet: Readonly<EntityChangePacket>; actor: EntityActor; phase: 'prepare' | 'revalidate'; action?: StoredEntitySubjectAction }): Promise<void>;
  prepareRecycle?(clusterId: string, request: Extract<EntityChangeOperation, { kind: 'recycle' }>, actor: EntityActor): Promise<{
    graph: RecycleGraph; packets: EntityChangePacket[]; schemas: EntityWriteSchemaMaterial[];
    prerequisites: EntityChangePrerequisite[]; metadataObligations: EntityChangeMetadataObligation[];
  }>;
  assertRecycleCurrent?(clusterId: string, request: Extract<EntityChangeOperation, { kind: 'recycle' }>, material: PreparedEntityChange, actor: EntityActor, context?: { action: StoredEntitySubjectAction; mode: 'fresh' }): Promise<void>;
  /** Fixed Root-owned current-identity/grant verifier for the authenticated
   * entire sealed subject. Historical mode authorizes frozen before/after
   * graphs; it never treats normal execution changes as material corruption.
   * The callback supplies no actor, permit or substitute source material. */
  assertStoredSubject?(input: { material: Readonly<PreparedEntityChange>; actor: EntityActor; action: StoredEntitySubjectAction; mode: 'historical' | 'fresh' }): Promise<void>;
}
